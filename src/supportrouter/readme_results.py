"""README results block and the README honesty check (Phase 12).

The README results section is generated from files in `reports/` between two markers, never
typed by hand. `--check` (CI) fails when:
- the block between the markers differs from a fresh build (a number was edited or a report
  changed without `make readme-results`);
- any decimal number in the rest of the README (prose) does not appear in the generated block,
  so a hand-typed "0.99" in a sentence cannot slip in either.
Run: `make readme-results` (write) or `make readme-check` (check).
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

from supportrouter.config import Config, load_config

START = "<!-- results:start (generated by `make readme-results` from reports/) -->"
END = "<!-- results:end -->"
# A number with a decimal point (0.9977, 1,647.49, 26.47); integers such as 27 or 300 are counts.
_DECIMAL = re.compile(r"(?<![\w.])\d[\d,]*\.\d+")
# Code spans and blocks hold versions and commands (`python 3.11`), not results.
_CODE = re.compile(r"```.*?```|`[^`\n]*`", re.DOTALL)


def _load(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _f(value: float, digits: int = 4) -> str:
    return f"{value:,.{digits}f}"


def build_results_block(cfg: Config) -> str:
    reports = cfg.evaluation.reports_dir.parent  # reports/
    metrics = cfg.evaluation.reports_dir  # reports/metrics/
    m = {p.stem: _load(p) for p in sorted(metrics.glob("*.json"))}
    test_rows = m["t1"]["test_rows"]

    lines = [
        START,
        "",
        f"**Frozen test split ({test_rows:,} messages, 27 intents, 1 seed).** "
        "Latency: single message, warm, CPU, predict only.",
        "",
        "| Model | Intent macro-F1 | Accuracy | Category macro-F1 | p95 ms | Size MB |",
        "|---|---|---|---|---|---|",
    ]
    rows = [
        ("B0 majority class", "b0"),
        ("B1 TF-IDF + LogReg (SAMPLE 3,000)", "b1-sample3000"),
        ("B1 TF-IDF + LogReg (FULL)", "b1"),
        ("T1 DistilBERT (SAMPLE 3,000, CPU)", "t1-sample3000"),
        ("T1 DistilBERT (FULL, Colab) — served", "t1"),
    ]
    for name, key in rows:
        r = m[key]
        p95 = "–" if key == "b0" else _f(r["latency"]["latency_p95_ms"], 2)
        size = "–" if key == "b0" else _f(r["model_size_bytes"] / 1e6, 2)
        lines.append(
            f"| {name} | {_f(r['metrics']['intent_macro_f1'])} | "
            f"{_f(r['metrics']['intent_accuracy'])} | {_f(r['metrics']['category_macro_f1'])} | "
            f"{p95} | {size} |"
        )

    lines += [
        "",
        "**Seeded 300-message test subset** (same messages for every row; LLM = local "
        "`mistral` 7B via Ollama on CPU).",
        "",
        "| Model | Intent macro-F1 | Accuracy | p95 ms | Cost / 1k msgs | Invalid outputs |",
        "|---|---|---|---|---|---|",
    ]
    for name, key in [
        ("B1 TF-IDF + LogReg (FULL)", "b1-subset300"),
        ("T1 DistilBERT (FULL)", "t1-subset300"),
        ("L1 LLM zero-shot", "l1-ollama-mistral-latest"),
        ("L2 LLM few-shot", "l2-ollama-mistral-latest"),
    ]:
        r = m[key]
        llm = r.get("llm")
        p95 = llm["latency_p95_ms"] if llm else r["latency"]["latency_p95_ms"]
        cost = f"${_f(llm['cost_per_1k_usd'], 2)}" if llm else "–"
        invalid = f"{_f(100 * llm['invalid_rate'], 1)}%" if llm else "–"
        lines.append(
            f"| {name} | {_f(r['metrics']['intent_macro_f1'])} | "
            f"{_f(r['metrics']['intent_accuracy'])} | {_f(p95, 2)} | {cost} | {invalid} |"
        )

    typos = _load(reports / "robustness_typos.json")
    lines += [
        "",
        "**Robustness: seeded synthetic typos on the full test split** (accuracy).",
        "",
        "| Typo rate per word | B1 FULL | T1 FULL |",
        "|---|---|---|",
    ]
    for rate in ["0.0", *[str(r) for r in typos["rates"]]]:
        b1 = typos["models"]["b1"]["scores"][rate]["accuracy"]
        t1 = typos["models"]["t1"]["scores"][rate]["accuracy"]
        lines.append(f"| {rate} | {_f(b1)} | {_f(t1)} |")

    api = _load(reports / "api_latency.json")
    gate = _load(reports / "quality_gate.json")
    drift = _load(cfg.monitoring.report_dir / "summary.json")
    batches = {b["batch"]: b for b in drift["batches"]}
    shifted, normal = batches["shifted"], batches["normal"]
    lat = api["latency"]
    lines += [
        "",
        "**Serving and MLOps.**",
        "",
        "| Check | Result | Source |",
        "|---|---|---|",
        f"| API `POST /classify`, T1, warm, over HTTP | p50 {_f(lat['latency_p50_ms'], 2)} ms, "
        f"p95 {_f(lat['latency_p95_ms'], 2)} ms (target {_f(api['target_p95_ms'], 0)}) | "
        "`reports/api_latency.json` |",
        f"| CI quality gate, B1 SAMPLE on validation | macro-F1 "
        f"{_f(gate['val_intent_macro_f1'])} vs threshold {gate['threshold']} → "
        f"{'PASS' if gate['passed'] else 'FAIL'} | `reports/quality_gate.json` |",
        f"| Drift report, shifted batch | {shifted['drifted_columns']}/{len(shifted['columns'])} "
        f"columns drifted → dataset drift {shifted['dataset_drift']} | "
        "`reports/drift/summary.json` |",
        f"| Drift report, normal batch | {normal['drifted_columns']}/{len(normal['columns'])} "
        f"columns drifted → dataset drift {normal['dataset_drift']} | "
        "`reports/drift/summary.json` |",
        "",
        f"Hardware: {m['t1']['hardware']['cpu']}, {m['t1']['hardware']['cores']} cores.",
        "",
        END,
    ]
    return "\n".join(lines)


def _split(text: str) -> tuple[str, str, str]:
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise ValueError("README must contain the results markers exactly once, in order")
    head, rest = text.split(START, 1)
    block, tail = rest.split(END, 1)
    return head, START + block + END, tail


def write_results(cfg: Config, readme: Path) -> None:
    head, _, tail = _split(readme.read_text(encoding="utf-8"))
    readme.write_text(head + build_results_block(cfg) + tail, encoding="utf-8")


def check_readme(cfg: Config, readme: Path) -> list[str]:
    """Return a list of README problems (empty = honest)."""
    head, block, tail = _split(readme.read_text(encoding="utf-8"))
    fresh = build_results_block(cfg)
    problems = []
    if block != fresh:
        problems.append("results block differs from reports/ (run `make readme-results`)")
    allowed = set(_DECIMAL.findall(fresh))
    prose = _CODE.sub(" ", head + tail)
    problems += [
        f"number {n!r} in README prose is not in the generated results block"
        for n in sorted(set(_DECIMAL.findall(prose)) - allowed)
    ]
    return problems


def main(argv: list[str] | None = None, cfg: Config | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check only (CI); exit 1 on problems")
    parser.add_argument("--readme", type=Path, default=None)
    args = parser.parse_args(argv)
    cfg = cfg or load_config()
    readme = args.readme or cfg.evaluation.reports_dir.parent.parent / "README.md"
    if not args.check:
        write_results(cfg, readme)
    problems = check_readme(cfg, readme)
    for p in problems:
        print(f"README check: {p}")
    print("README check:", "FAIL" if problems else "PASS")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
